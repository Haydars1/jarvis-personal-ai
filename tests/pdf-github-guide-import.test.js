test('30 Sep 2026 PDF guide imports every unique GitHub repository', () => {
  assert.equal(PDF_GUIDE_REPOS.length, 141);
  const seeded = new Set(CURATED_CAPABILITY_SEEDS.map(item => item.repo));
  const missing = PDF_GUIDE_REPOS.filter(repo => !seeded.has(repo));
  assert.deepEqual(missing, [], `missing PDF guide repositories: ${missing.join(', ')}`);
});

test('PDF guide import keeps every seed uniquely addressable', () => {
  const seeded = CURATED_CAPABILITY_SEEDS.map(item => item.repo);
  assert.equal(new Set(seeded).size, seeded.length, 'curated seed list must not contain duplicate repository IDs');
});
